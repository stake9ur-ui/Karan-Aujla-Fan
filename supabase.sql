create table if not exists public.fan_content (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('song','album','video','photo','timeline','concert','lyrics','award','fan')),
  title text not null,
  subtitle text,
  description text,
  image_url text,
  youtube_url text,
  spotify_url text,
  date text,
  link text,
  created_at timestamptz not null default now()
);

alter table public.fan_content enable row level security;

drop policy if exists "Public can read fan content" on public.fan_content;
create policy "Public can read fan content"
on public.fan_content for select
to anon, authenticated
using (true);

drop policy if exists "Only owner can insert fan content" on public.fan_content;
create policy "Only owner can insert fan content"
on public.fan_content for insert
to authenticated
with check ((auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');

drop policy if exists "Only owner can update fan content" on public.fan_content;
create policy "Only owner can update fan content"
on public.fan_content for update
to authenticated
using ((auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL')
with check ((auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');

drop policy if exists "Only owner can delete fan content" on public.fan_content;
create policy "Only owner can delete fan content"
on public.fan_content for delete
to authenticated
using ((auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');

-- Optional public artwork bucket. Use licensed/owned media only.
insert into storage.buckets (id, name, public)
values ('fan-artwork', 'fan-artwork', true)
on conflict (id) do nothing;

drop policy if exists "Public can view fan artwork" on storage.objects;
create policy "Public can view fan artwork"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'fan-artwork');

drop policy if exists "Only owner can upload fan artwork" on storage.objects;
create policy "Only owner can upload fan artwork"
on storage.objects for insert
to authenticated
with check (bucket_id = 'fan-artwork' and (auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');

drop policy if exists "Only owner can update fan artwork" on storage.objects;
create policy "Only owner can update fan artwork"
on storage.objects for update
to authenticated
using (bucket_id = 'fan-artwork' and (auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL')
with check (bucket_id = 'fan-artwork' and (auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');

drop policy if exists "Only owner can delete fan artwork" on storage.objects;
create policy "Only owner can delete fan artwork"
on storage.objects for delete
to authenticated
using (bucket_id = 'fan-artwork' and (auth.jwt() ->> 'email') = 'YOUR_OWNER_EMAIL');
