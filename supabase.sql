-- 1. CREATE CONTENT TABLE
create table if not exists public.fan_content (
  id bigint generated by default as identity primary key,
  type text not null check (
    type in (
      'song',
      'album',
      'video',
      'photo',
      'timeline',
      'concert',
      'lyrics',
      'award',
      'fan'
    )
  ),
  title text not null,
  subtitle text,
  description text,
  image_url text,
  youtube_url text,
  spotify_url text,
  date text,
  link text,
  created_at timestamptz not null default now()
);

-- 2. ENABLE SECURITY
alter table public.fan_content
enable row level security;

-- 3. PUBLIC READ ACCESS
drop policy if exists "Public can read fan content"
on public.fan_content;

create policy "Public can read fan content"
on public.fan_content
for select
to anon, authenticated
using (true);

-- 4. OWNER ONLY INSERT
drop policy if exists "Only owner can insert fan content"
on public.fan_content;

create policy "Only owner can insert fan content"
on public.fan_content
for insert
to authenticated
with check (
  (auth.jwt() ->> 'email') = 'officialdarshan24@gmail.com'
);

-- 5. OWNER ONLY UPDATE
drop policy if exists "Only owner can update fan content"
on public.fan_content;

create policy "Only owner can update fan content"
on public.fan_content
for update
to authenticated
using (
  (auth.jwt() ->> 'email') = 'officialdarshan24@gmail.com'
)
